/* =========================
   GITHUB PAGES NAVIGATION
========================= */

function getSiteBase() {

  /*
   * GitHub Pages project:
   * https://djrcomptabilite-max.github.io/work-and-worth/
   *
   * إذا تم استعمال الدومين الخاص لاحقًا:
   * https://workandworth.dz/
   *
   * سيتم استعمال المسار الجذري تلقائيًا.
   */

  if (window.location.hostname.endsWith("github.io")) {
    return "/work-and-worth/";
  }

  return "/";
}


function navigateToPage(page) {

  const base = getSiteBase();

  const cleanPage =
    String(page || "index.html")
      .replace(/^\/+/, "")
      .replace(/^work-and-worth\//, "");

  window.location.assign(
    base + cleanPage
  );
}


function initNavigation() {

  document.querySelectorAll("a[href]").forEach(link => {

    const href = link.getAttribute("href");

    if (!href) return;

    /*
     * لا نتدخل في:
     * mailto:
     * tel:
     * http:
     * https:
     * #anchors
     */

    if (
      href.startsWith("mailto:") ||
      href.startsWith("tel:") ||
      href.startsWith("#") ||
      href.startsWith("http://") ||
      href.startsWith("https://")
    ) {
      return;
    }

    /*
     * الروابط الداخلية للموقع
     */

    const page =
      href.split("#")[0].split("?")[0];

    if (!page) return;

    link.addEventListener("click", function(event) {

      event.preventDefault();

      navigateToPage(page);

    });

  });

}


/* =========================
   LANGUAGE
========================= */

function setLang(lang) {

  const t = translations[lang] || translations.fr;

  document.documentElement.lang = lang;

  document.documentElement.dir =
    lang === "ar" ? "rtl" : "ltr";

  document.body.classList.toggle(
    "rtl",
    lang === "ar"
  );

  document.querySelectorAll("[data-i18n]").forEach(el => {

    const key = el.dataset.i18n;

    if (
      Object.prototype.hasOwnProperty.call(t, key)
    ) {
      el.textContent = t[key];
    }

  });


  document.querySelectorAll(
    "[data-i18n-placeholder]"
  ).forEach(el => {

    const key =
      el.dataset.i18nPlaceholder;

    if (
      Object.prototype.hasOwnProperty.call(t, key)
    ) {
      el.setAttribute(
        "placeholder",
        t[key]
      );
    }

  });


  document.querySelectorAll(
    "[data-lang-btn]"
  ).forEach(button => {

    const active =
      button.dataset.langBtn === lang;

    button.classList.toggle(
      "active",
      active
    );

    button.setAttribute(
      "aria-pressed",
      active ? "true" : "false"
    );

  });

  localStorage.setItem(
    "ww_lang",
    lang
  );

}


/* =========================
   MOBILE MENU
========================= */

function initMobileMenu() {

  const hamburger =
    document.querySelector(".hamb");

  const nav =
    document.querySelector("header nav");

  if (!hamburger || !nav) return;

  hamburger.setAttribute(
    "aria-expanded",
    "false"
  );


  hamburger.addEventListener(
    "click",
    function(event) {

      event.preventDefault();

      const opened =
        nav.classList.toggle("open");

      hamburger.setAttribute(
        "aria-expanded",
        opened ? "true" : "false"
      );

    }
  );


  nav.querySelectorAll("a").forEach(
    link => {

      link.addEventListener(
        "click",
        function() {

          nav.classList.remove("open");

          hamburger.setAttribute(
            "aria-expanded",
            "false"
          );

        }
      );

    }
  );

}


/* =========================
   CURRENT PAGE
========================= */

function setCurrentPage() {

  let currentFile =
    window.location.pathname
      .split("/")
      .pop();

  if (!currentFile) {
    currentFile = "index.html";
  }

  document
    .querySelectorAll("header nav a")
    .forEach(link => {

      const href =
        link.getAttribute("href");

      if (!href) return;

      const linkFile =
        href
          .split("/")
          .pop()
          .split("#")[0]
          .split("?")[0];

      link.classList.toggle(
        "current",
        linkFile === currentFile
      );

    });

}


/* =========================
   LANGUAGE BUTTONS
========================= */

function initLanguages() {

  document
    .querySelectorAll("[data-lang-btn]")
    .forEach(button => {

      button.addEventListener(
        "click",
        function(event) {

          event.preventDefault();
          event.stopPropagation();

          const lang =
            this.dataset.langBtn;

          if (translations[lang]) {
            setLang(lang);
          }

        }
      );

    });

}


/* =========================
   FORMS
========================= */

function initForms() {

  document
    .querySelectorAll("form.form")
    .forEach(form => {

      /*
       * إضافة أسماء للحقول تلقائيًا
       * لأن بعض صفحات HTML لا تحتوي
       * على name=""
       */

      const inputs =
        form.querySelectorAll("input");

      if (inputs[0])
        inputs[0].setAttribute(
          "name",
          "name"
        );

      if (inputs[1])
        inputs[1].setAttribute(
          "name",
          "company"
        );

      if (inputs[2])
        inputs[2].setAttribute(
          "name",
          "email"
        );

      if (inputs[3])
        inputs[3].setAttribute(
          "name",
          "phone"
        );

      const textarea =
        form.querySelector("textarea");

      if (textarea)
        textarea.setAttribute(
          "name",
          "message"
        );


      form.addEventListener(
        "submit",
        function(event) {

          event.preventDefault();

          const name =
            form
              .querySelector('[name="name"]')
              ?.value
              .trim() || "";

          const company =
            form
              .querySelector('[name="company"]')
              ?.value
              .trim() || "";

          const email =
            form
              .querySelector('[name="email"]')
              ?.value
              .trim() || "";

          const phone =
            form
              .querySelector('[name="phone"]')
              ?.value
              .trim() || "";

          const message =
            form
              .querySelector('[name="message"]')
              ?.value
              .trim() || "";


          if (!name) {

            alert(
              "Veuillez saisir votre nom et prénom."
            );

            return;
          }


          if (
            !email ||
            !email.includes("@")
          ) {

            alert(
              "Veuillez saisir une adresse e-mail valide."
            );

            return;
          }


          if (!message) {

            alert(
              "Veuillez préciser votre besoin."
            );

            return;
          }


          const subject =
            encodeURIComponent(
              "Work & Worth - Demande"
            );


          const body =
            encodeURIComponent(
`Nom et prénom : ${name}
Entreprise : ${company}
E-mail : ${email}
Téléphone : ${phone}

Besoin :
${message}`
            );


          window.location.href =
            `mailto:djerraya.entreprise@hotmail.com?subject=${subject}&body=${body}`;

        }
      );

    });

}


/* =========================
   INITIALISATION
========================= */

document.addEventListener(
  "DOMContentLoaded",
  function() {

    const savedLang =
      localStorage.getItem("ww_lang") || "fr";

    setLang(savedLang);

    initMobileMenu();

    initLanguages();

    setCurrentPage();

    initNavigation();

    initForms();

  }
);
